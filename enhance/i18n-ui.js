const ENH_LANG = (function () {
  try {
    const q = new URLSearchParams(location.search).get('lang');
    if (q && ENH_I18N[q]) { localStorage.setItem('enh_lang', q); return q; }
    const s = localStorage.getItem('enh_lang');
    if (s && ENH_I18N[s]) return s;
  } catch (e) {}
  const l = (navigator.language || '').toLowerCase();
  if (l.startsWith('zh')) return 'tw';
  if (l.startsWith('ko')) return 'ko';
  return 'en';
})();

// 키가 없으면 한국어로 폴백한다. 화면이 'undefined'로 깨지는 것보다 낫다.
function T(k) {
  const v = ENH_I18N[ENH_LANG] && ENH_I18N[ENH_LANG][k];
  return v !== undefined ? v : (ENH_I18N.ko[k] !== undefined ? ENH_I18N.ko[k] : k);
}
function enhSetLang(l) {
  try { localStorage.setItem('enh_lang', l); } catch (e) {}
  location.search = '?lang=' + l;
}
function enhNextLang() {
  const order = ['ko', 'en', 'tw'];
  enhSetLang(order[(order.indexOf(ENH_LANG) + 1) % order.length]);
}
