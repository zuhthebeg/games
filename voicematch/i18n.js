function detectLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q && I18N[q]) return q;
  // /voicematch/es/ 같은 경로형 진입(OG 메타를 언어별로 주기 위한 페이지)
  const p = location.pathname.match(/\/voicematch\/([a-z]{2})\/?$/);
  if (p && I18N[p[1]]) return p[1];
  const saved = localStorage.getItem('vm_lang');
  if (saved && I18N[saved]) return saved;
  const navFull = (navigator.language || 'ko').toLowerCase();
  if (navFull.startsWith('zh')) return 'tw';
  const nav = navFull.slice(0, 2);
  return I18N[nav] ? nav : 'en';
}
function singerName(s, lang) {
  if (lang === 'ko') return s.name;
  const base = (lang === 'tw' && TW_NAMES[s.slug]) ? TW_NAMES[s.slug] : (EN_NAMES[s.slug] || s.name);
  if (lang === 'tw' && s.group && window._singersCache) {
    const g = window._singersCache.find(x => x.slug === s.group);
    if (g) return `${base}（${singerName(g, lang)}）`;
  }
  return base;
}
function genreLabel(genre, lang) {
  if (lang === 'ko') return genre;
  const m = GENRE_MAP[lang] || GENRE_MAP.en;
  return genre.split('·').map(t => m[t.trim()] || t.trim()).join(' · ');
}
